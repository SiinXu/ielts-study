# zh-Hant 运行时补充转换：单字表 + 歧义双字短语（由 OpenCC s2t 对全站中文文本整句转换比对得出）
import re,glob,json,opencc
SITE='/workspace/ielts-pages'; cc=opencc.OpenCC('s2t')
txt=[]
for f in [SITE+'/data.js',SITE+'/app.js',SITE+'/study.js',SITE+'/words.js']+glob.glob(SITE+'/content/*.js'):
    txt+=re.findall(r'[\u3000-\u303f\u4e00-\u9fff\uff00-\uffef]+',open(f,encoding='utf-8').read())
chars=sorted(set(''.join(txt)))
C={c:cc.convert(c) for c in chars if len(cc.convert(c))==1 and cc.convert(c)!=c}
def cm(s): return ''.join(C.get(c,c) for c in s)
from collections import Counter,defaultdict
PC=defaultdict(Counter)
for s in set(txt):
    f=cc.convert(s)
    if len(f)!=len(s): continue
    m=cm(s)
    for i in range(len(s)):
        if f[i]!=m[i]:
            a=max(0,i-1); seg=s[a:i+1] if i>0 else s[i:i+2]
            ff=f[a:i+1] if i>0 else f[i:i+2]
            if len(seg)==2: PC[seg][ff]+=1
AC=defaultdict(Counter)
for s in set(txt):
    f=cc.convert(s)
    if len(f)!=len(s): continue
    for k in PC:
        st=s.find(k)
        while st>=0: AC[k][f[st:st+2]]+=1; st=s.find(k,st+1)
P={k:c.most_common(1)[0][0] for k,c in AC.items() if c.most_common(1)[0][0]!=cm(k)}
# 验证：短语+单字 与整句 OpenCC 的一致率
def conv(s):
    out=[];i=0
    while i<len(s):
        if s[i:i+2] in P: out.append(P[s[i:i+2]]); i+=2
        else: out.append(C.get(s[i],s[i])); i+=1
    return ''.join(out)
U=list(set(txt)); okn=sum(conv(s)==cc.convert(s) for s in U)
print('chars',len(C),'phrases',len(P),'sentence match %d/%d'%(okn,len(U)))
js='''/* generated by i18n-src/build_zht_conv.py：繁體中文頁面上未經字典的簡體文字，按「短語優先、單字其次」即時轉換 */
(function(){
var C=%s, P=%s;
function cv(s){ if(!/[\\u4e00-\\u9fff]/.test(s)) return s; var o='',i=0; while(i<s.length){ var two=s.substr(i,2); if(P[two]){o+=P[two];i+=2;} else {o+=C[s[i]]||s[i];i++;} } return o; }
var AT=['placeholder','title','aria-label','alt'];
function walk(n){
  if(n.nodeType===3){ var v=n.nodeValue, w=cv(v); if(w!==v) n.nodeValue=w; return; }
  if(n.nodeType!==1 || /^(SCRIPT|STYLE|TEXTAREA|INPUT)$/.test(n.nodeName) || (n.nodeName===\'OPTION\' && n.value===\'zh\')) return;
  for(var a=0;a<AT.length;a++){ var x=n.getAttribute&&n.getAttribute(AT[a]); if(x){ var y=cv(x); if(y!==x) n.setAttribute(AT[a],y); } }
  for(var c=n.firstChild;c;c=c.nextSibling) walk(c);
}
window.I18N_ZHT={cv:cv};
function start(){ walk(document.body); document.title=cv(document.title);
  new MutationObserver(function(ms){ for(var i=0;i<ms.length;i++){ var m=ms[i];
    if(m.type==='characterData') walk(m.target); else if(m.type==='attributes') walk(m.target); else for(var j=0;j<m.addedNodes.length;j++) walk(m.addedNodes[j]); } })
  .observe(document.body,{childList:true,subtree:true,characterData:true,attributes:true,attributeFilter:AT}); }
if(document.body) start(); else document.addEventListener('DOMContentLoaded',start);
})();
'''%(json.dumps(C,ensure_ascii=False,separators=(',',':')),json.dumps(P,ensure_ascii=False,separators=(',',':')))
open(SITE+'/i18n/zh-Hant-conv.js','w',encoding='utf-8').write(js)
