# v10：新增 zh-Hant / vi / fr / de 界面语言 + 听力陷阱说明 10 语
import json,re,glob,os,subprocess,opencc
SRC=os.path.dirname(os.path.abspath(__file__)); SITE='/workspace/ielts-pages'
cc=opencc.OpenCC('s2twp')
D=json.load(open('/tmp/ielts_i18n.json'))          # 现有 en/ja/ko/es/ms（node 读出）
keys=json.load(open('/tmp/ui_keys.json'))           # 586 条界面串（ja 已覆盖的集合）
def rd(f,n):
    out={}
    for ln in open(os.path.join(SRC,f),encoding='utf-8'):
        if not ln.strip(): continue
        p=[x.strip() for x in ln.rstrip('\n').split(' ¦ ')]
        assert len(p)==n+1,(f,ln[:60],len(p)); out[int(p[0])]=p[1:]
    return out
ui={}
for f in ['t_vfd1.txt','t_vfd2.txt','t_vfd3.txt','t_vfd4.txt']: ui.update(rd(f,3))
assert sorted(ui)==list(range(len(keys))),(len(ui),len(keys))
NEW={l:{} for l in ['vi','fr','de']}
for i,k in enumerate(keys):
    for j,l in enumerate(['vi','fr','de']):
        v=ui[i][j]
        if D['en'].get(k,'').strip()==',' : v=D['en'][k]
        NEW[l][k]=v
# 占位符检查
bad=[(l,k) for l in NEW for k,v in NEW[l].items() if sorted(re.findall(r'\{\w+\}',v))!=sorted(re.findall(r'\{\w+\}',D['en'].get(k,k)))]
print('placeholder mismatches',bad[:10],len(bad))
# 陷阱：中文源 78 条 → ja ko es ms vi fr de
tz=json.load(open('/tmp/traps_zh.json')); T1=rd('t_traps_zh.txt',7); assert len(T1)==len(tz)
TL=['ja','ko','es','ms','vi','fr','de']
TR={l:{} for l in TL+['zh','en']}
for i,k in enumerate(tz):
    for j,l in enumerate(TL): TR[l][k]=T1[i][j]
# 陷阱：英文原句 24 条 → zh en ja ko es ms vi fr de
te=[ln.split(' ¦ ')[1].strip() for ln in subprocess.run(['node','/tmp/tr.js'],cwd=SITE,capture_output=True,text=True).stdout.splitlines()]
T2=rd('t_traps_en.txt',9); assert len(T2)==len(te)
for i,k in enumerate(te):
    for j,l in enumerate(['zh','en']+TL): TR[l][k]=T2[i][j]
# zh-Hant：所有会经过 T() 的中文串 + related 系列里的中文 + 陷阱
lit=set()
for f in ['app.js','study.js','words.js']+glob.glob(SITE+'/content/related*.js'):
    code=open(os.path.join(SITE,f) if not f.startswith('/') else f,encoding='utf-8').read()
    for m in re.finditer(r"'((?:\\.|[^'\\\n])*)'|\"((?:\\.|[^\"\\\n])*)\"",code):
        s=(m.group(1) if m.group(1) is not None else m.group(2)).replace("\\'","'").replace('\\"','"')
        if re.search('[\u4e00-\u9fff]',s): lit.add(s.strip())
zht={}
for k in list(D['en'].keys())+list(lit)+tz:
    if re.search('[\u4e00-\u9fff]',k): zht[k]=cc.convert(k)
for k in te: zht[k]=cc.convert(TR['zh'][k])
for k,v in list(zht.items()):
    if v==k: del zht[k]   # 简繁同形不必存
print('zh-Hant entries',len(zht))
hdr='/* generated by i18n-src/build_v10.py — key = original string */\n'
def w(l,o,name=None):
    open(f'{SITE}/i18n/{name or l}.js','w',encoding='utf-8').write(hdr+'I18N.add(%s, %s);\n'%(json.dumps(l),json.dumps(o,ensure_ascii=False,indent=0)))
w('zh-Hant',zht)
for l in ['vi','fr','de']: w(l,{**NEW[l],**TR[l]})
w('zh',TR['zh'])
# 现有语言追加陷阱块（幂等）
M='/* traps v10 */'
for l in ['en','ja','ko','es','ms']:
    p=f'{SITE}/i18n/{l}.js'; s=open(p,encoding='utf-8').read()
    if M in s: s=s[:s.index(M)]
    s+=M+'\nI18N.add(%s, %s);\n'%(json.dumps(l),json.dumps(TR[l],ensure_ascii=False,indent=0))
    open(p,'w',encoding='utf-8').write(s)
print({l:len(NEW[l])+len(TR[l]) for l in NEW}, 'traps',{l:len(TR[l]) for l in TR})
