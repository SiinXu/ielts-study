#!/usr/bin/env python3
"""English for the Chinese study notes in data.js, used on every non-Chinese page (zh / zh-Hant keep the
original; other locales fall back to English exactly like i18n/core.js does for UI strings).
Segments = text between HTML tags that contains Han. Translations live in tools/data_en.json (hand-written,
keyed by the Chinese segment); segments already in the UI dictionary (i18n/*.js) are translated at runtime
per locale and are skipped here. Output: content/data-en.js (window.DATA_EN, ASCII-escaped).
Run after data.js changes: python3 tools/data_i18n.py  (lists any new segment that still needs English;
at runtime an untranslated segment has its Han stripped, so non-Chinese pages never show Chinese)."""
import json, os, re, subprocess
D = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(D, '..')
H = re.compile(r'[\u4e00-\u9fff\u3400-\u4dbf]')
raw = open(os.path.join(R, 'data.js'), encoding='utf-8').read(); d = json.loads(raw[raw.index('{'):raw.rindex('}') + 1])
segs = set()
def add(h):
    if not h: return
    for t in re.split(r'<[^>]+>', h):
        if H.search(t): segs.add(t.strip())
add(d.get('cover'))
for s in d['sections']:
    for k in ('short', 'title', 'source'): add(s.get(k))
    for n in s['nodes']:
        add(n.get('text')); add(n.get('html')); add(n.get('title'))
        for c in n.get('cells') or []: add(c['html']); add(c.get('label'))
ui = json.loads(subprocess.run(['node', '-e', "var D={};global.I18N={add:(l,o)=>{D[l]=Object.assign(D[l]||{},o)}};require('" + os.path.join(R, 'i18n', 'en.js') + "');process.stdout.write(JSON.stringify(D.en))"], capture_output=True, text=True, check=True).stdout)
EN = json.load(open(os.path.join(D, 'data_en.json'), encoding='utf-8'))
bad = [k for k, v in EN.items() if H.search(v)]
assert not bad, f'Han in English output: {bad[:5]}'
out = {k: EN[k] for k in sorted(segs) if k in EN}
todo = [k for k in sorted(segs) if k not in EN and k not in ui]
open(os.path.join(R, 'content', 'data-en.js'), 'w', encoding='utf-8').write(
    '/* generated by tools/data_i18n.py: English for the Chinese study notes in data.js (non-zh pages) */\nwindow.DATA_EN=' + json.dumps(out, ensure_ascii=True, separators=(',', ':')) + ';\n')
print(f'segments {len(segs)}, english {len(out)}, via UI dictionary {len(segs) - len(out) - len(todo)}, missing {len(todo)}')
for k in todo[:30]: print('  needs English:', k)
